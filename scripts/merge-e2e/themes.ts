// The --vscode-* values a VS Code webview is given, per built-in theme, for
// every token the merge webview reads (packages/webview-ui/src: diff.css,
// shell.css, tokens.css, hostTokens.ts, theme.ts …). VS Code injects these on
// <html>/<body> of every webview; a headless render that supplies only three of
// them (the unit tests' page) paints the chrome from fallbacks no user sees.
//
// Values are VS Code's defaults for "Dark+ (default dark)", "Light+ (default
// light)", "Dark High Contrast" and "Light High Contrast" (the colorRegistry
// defaults plus the themes' own overrides). A token a theme leaves undefined is
// left out here too, so a `var(--x, fallback)` behaves as it does in VS Code.

export type VsCodeTheme = "dark" | "light" | "hc-dark" | "hc-light";

