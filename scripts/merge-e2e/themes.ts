/** The inline style VS Code would put on the webview body. */
export function bodyStyle(theme: VsCodeTheme): string {
  return Object.entries(VSCODE_THEMES[theme])
    .map(([k, v]) => `${k}:${v.replace(/"/g, "&quot;")}`)
    .join(";");
}
